#!/usr/bin/env python3
"""Turn a firmware blob into a C source the kext links in.

usage: embed-firmware.py <firmware.bin|-> <out.c> <name>
Passing '-' (or a missing file with --allow-missing) emits an empty stub so the kext still
builds; M3 then reports `xe2-guc = no-firmware-embedded`.
"""
import os
import sys


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    allow_missing = "--allow-missing" in sys.argv
    if len(args) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src, out, name = args
    data = b""
    if src != "-":
        if os.path.exists(src):
            with open(src, "rb") as f:
                data = f.read()
        elif not allow_missing:
            print(f"error: {src} not found (run tools/fetch-firmware.sh)", file=sys.stderr)
            return 1
        else:
            print(f"warning: {src} not found, embedding empty GuC firmware stub", file=sys.stderr)

    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w") as f:
        f.write("// Generated by tools/embed-firmware.py - do not edit.\n")
        f.write("// Firmware: Intel linux-firmware, see LICENSE.xe (redistributable in binary form).\n")
        f.write(f'const char clawxe2_guc_fw_name[] = "{name}";\n')
        f.write(f"const unsigned int clawxe2_guc_fw_len = {len(data)}u;\n")
        f.write("__attribute__((aligned(4096))) const unsigned char clawxe2_guc_fw[")
        f.write(f"{max(len(data), 1)}] = {{\n")
        for i in range(0, len(data), 16):
            f.write("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
        if not data:
            f.write("  0\n")
        f.write("};\n")
    print(f"{out}: {name}, {len(data)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
